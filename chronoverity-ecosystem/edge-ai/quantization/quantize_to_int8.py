"""
quantize_to_int8.py
-------------------------------------------------------------------------
Converts the trained Keras model (pqi_model.h5, from
edge-ai/training/train_pqi_model.py) into a fully INT8-quantized
TFLite Micro model, then emits a C byte array so it can be linked
directly into firmware/core-mcu/tinyml/pqi_inference.c without a
filesystem on the target.

Usage:
    python quantize_to_int8.py --model ../training/pqi_model.h5 \
                                --data ../datasets/synthetic_pqi_dataset.csv \
                                --out pqi_model_int8.tflite
"""

import argparse

import numpy as np
import pandas as pd
import tensorflow as tf

FEATURE_NAMES = [
    "thermal_integral",
    "shock_peak_g",
    "shock_event_count",
    "voc_slope",
    "spectral_delta",
    "core_ambient_diff",
]


def representative_dataset_gen(x_sample: np.ndarray):
    for i in range(min(300, len(x_sample))):
        yield [x_sample[i : i + 1].astype(np.float32)]


def convert_to_int8_tflite(model_path: str, x_sample: np.ndarray) -> bytes:
    model = tf.keras.models.load_model(model_path)

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = lambda: representative_dataset_gen(x_sample)
    # Full integer quantization: both input and output tensors become
    # INT8, which is required for the TFLite Micro kernels ChronoCase's
    # MicroMutableOpResolver links against (see pqi_inference.c's TODO).
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8

    return converter.convert()


def emit_c_array(tflite_bytes: bytes, out_header_path: str, var_name: str = "g_pqi_model_int8_tflite"):
    """Equivalent to `xxd -i`, referenced directly from pqi_inference.c."""
    with open(out_header_path, "w") as f:
        f.write("/* Auto-generated by edge-ai/quantization/quantize_to_int8.py. Do not edit by hand. */\n")
        f.write("#include <stddef.h>\n\n")
        f.write(f"const unsigned char {var_name}[] = {{\n")
        for i in range(0, len(tflite_bytes), 12):
            chunk = tflite_bytes[i : i + 12]
            f.write("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
        f.write("};\n")
        f.write(f"const unsigned int {var_name}_len = {len(tflite_bytes)};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True)
    parser.add_argument("--data", required=True, help="CSV used to build the representative dataset")
    parser.add_argument("--out", default="pqi_model_int8.tflite")
    parser.add_argument("--emit-c-array", action="store_true",
                         help="Also emit pqi_model_data.h for direct firmware linking")
    args = parser.parse_args()

    df = pd.read_csv(args.data)
    x_sample = df[FEATURE_NAMES].values.astype(np.float32)

    tflite_bytes = convert_to_int8_tflite(args.model, x_sample)

    with open(args.out, "wb") as f:
        f.write(tflite_bytes)
    print(f"Wrote quantized model ({len(tflite_bytes)} bytes) to {args.out}")

    if args.emit_c_array:
        header_path = args.out.replace(".tflite", "_data.h")
        emit_c_array(tflite_bytes, header_path)
        print(f"Wrote C byte array to {header_path} for firmware/core-mcu/tinyml/ linking")


if __name__ == "__main__":
    main()
